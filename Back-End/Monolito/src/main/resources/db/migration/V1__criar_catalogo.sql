CREATE TABLE tb_categorias (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL
);

-- Unicidade sem diferenciar maiúsculas/minúsculas ("Carnes" e "carnes" são a mesma categoria)
CREATE UNIQUE INDEX uk_categorias_nome ON tb_categorias (lower(nome));

CREATE TABLE tb_produtos (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(120) NOT NULL,
    descricao      VARCHAR(1000),
    categoria_id   BIGINT NOT NULL,
    imagem_url     VARCHAR(2048),
    disponivel     BOOLEAN NOT NULL DEFAULT TRUE,
    data_cadastro  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    data_alteracao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT fk_produtos_categoria FOREIGN KEY (categoria_id) REFERENCES tb_categorias (id)
);

CREATE INDEX idx_produtos_categoria_id ON tb_produtos (categoria_id);
