-- Catálogo: categorias, alimentos (o que a cozinha tem) e produtos (o que é vendido)

CREATE TABLE tb_categorias (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(100) NOT NULL,
    -- grupo estável usado pelas regras da marmita; bebida e sobremesa são vendidas à parte
    grupo          VARCHAR(20) NOT NULL,
    CONSTRAINT ck_categorias_grupo CHECK (grupo IN
        ('CARNE', 'ARROZ', 'FEIJAO', 'MASSA', 'SALADA', 'ACOMPANHAMENTO', 'BEBIDA', 'SOBREMESA'))
);

-- Unicidade sem diferenciar maiúsculas/minúsculas ("Carnes" e "carnes" são a mesma categoria)
CREATE UNIQUE INDEX uk_categorias_nome ON tb_categorias (lower(nome));

CREATE TABLE tb_alimentos (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(120) NOT NULL,
    descricao      VARCHAR(1000),
    categoria_id   BIGINT NOT NULL,
    imagem_url     VARCHAR(2048),
    disponivel     BOOLEAN NOT NULL DEFAULT TRUE,
    data_cadastro  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    data_alteracao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT fk_alimentos_categoria FOREIGN KEY (categoria_id) REFERENCES tb_categorias (id)
);

CREATE INDEX idx_alimentos_categoria_id ON tb_alimentos (categoria_id);

CREATE TABLE tb_produtos (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(120) NOT NULL,
    tipo           VARCHAR(20) NOT NULL,
    alimento_id    BIGINT,
    disponivel     BOOLEAN NOT NULL DEFAULT TRUE,
    data_cadastro  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    data_alteracao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT fk_produtos_alimento FOREIGN KEY (alimento_id) REFERENCES tb_alimentos (id),
    CONSTRAINT ck_produtos_tipo CHECK (tipo IN ('MARMITA', 'BEBIDA', 'SOBREMESA')),
    -- marmita não tem alimento ligado (composição escolhida no pedido); bebida e sobremesa têm
    CONSTRAINT ck_produtos_alimento CHECK (
        (tipo = 'MARMITA' AND alimento_id IS NULL) OR (tipo <> 'MARMITA' AND alimento_id IS NOT NULL))
);

CREATE INDEX idx_produtos_alimento_id ON tb_produtos (alimento_id);
CREATE UNIQUE INDEX uk_produtos_nome ON tb_produtos (lower(nome));

-- Preço de cada tamanho em que o produto é vendido.
-- Marmita: PEQUENA, MEDIA e GRANDE. Bebida e sobremesa: UNICO.
CREATE TABLE tb_produto_precos (
    produto_id BIGINT NOT NULL,
    tamanho    VARCHAR(10) NOT NULL,
    preco      NUMERIC(6, 2) NOT NULL,
    PRIMARY KEY (produto_id, tamanho),
    CONSTRAINT fk_produto_precos_produto FOREIGN KEY (produto_id) REFERENCES tb_produtos (id) ON DELETE CASCADE,
    CONSTRAINT ck_produto_precos_tamanho CHECK (tamanho IN ('UNICO', 'PEQUENA', 'MEDIA', 'GRANDE')),
    CONSTRAINT ck_produto_precos_preco CHECK (preco > 0)
);
